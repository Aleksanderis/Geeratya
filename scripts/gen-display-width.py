#!/usr/bin/env python3
"""Generate src/Geeratya.Core/Text/WideRanges.cs from the Unicode Character Database.

usage: gen-display-width.py [unicode-version]   (default 17.0.0)

Downloads EastAsianWidth.txt and emoji/emoji-data.txt from unicode.org, merges the
code points with East Asian Width W or F and Emoji_Presentation=Yes into sorted,
merged ranges, and writes them as a constant table. Run by hand when a new Unicode
version should be adopted; the build never downloads anything.
"""
import re
import sys
import urllib.request

VERSION = sys.argv[1] if len(sys.argv) > 1 else "17.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd"
OUTPUT = "src/Geeratya.Core/Text/WideRanges.cs"
LINE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)")


def fetch(path):
    with urllib.request.urlopen(f"{BASE}/{path}") as response:
        return response.read().decode("utf-8")


def ranges(text, accepted):
    for line in text.splitlines():
        match = LINE.match(line)
        if match and match.group(3) in accepted:
            first = int(match.group(1), 16)
            yield first, int(match.group(2) or match.group(1), 16)


points = sorted(
    list(ranges(fetch("EastAsianWidth.txt"), {"W", "F"}))
    + list(ranges(fetch("emoji/emoji-data.txt"), {"Emoji_Presentation"}))
)
merged = []

for first, last in points:
    if merged and first <= merged[-1][1] + 1:
        merged[-1][1] = max(merged[-1][1], last)
    else:
        merged.append([first, last])

rows = ",\n".join(f"        0x{first:X}, 0x{last:X}" for first, last in merged)

with open(OUTPUT, "w", encoding="utf-8", newline="\n") as output:
    output.write(
        f"""namespace Geeratya.Core.Text;

// <auto-generated> by scripts/gen-display-width.py from Unicode {VERSION}. Do not edit. </auto-generated>
internal static class WideRanges
{{
    /// <summary>First and last code point of each wide range, interleaved and sorted.</summary>
    public static ReadOnlySpan<int> Bounds =>
    [
{rows},
    ];
}}
"""
    )

print(f"{len(merged)} ranges from Unicode {VERSION}")
