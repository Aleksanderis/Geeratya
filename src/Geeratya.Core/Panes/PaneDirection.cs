namespace Geeratya.Core.Panes;

/// <summary>A direction pane focus moves in (<c>pane.focus-left</c> and its siblings).</summary>
public enum PaneDirection
{
    /// <summary>To the pane on the left.</summary>
    Left,

    /// <summary>To the pane below.</summary>
    Down,

    /// <summary>To the pane above.</summary>
    Up,

    /// <summary>To the pane on the right.</summary>
    Right,
}
